function augmenter = makeAugmenter(cfg)
% MAKEAUGMENTER Augmentations geometriques de P1 (rotation, flip, zoom,
% translation). La luminosite est appliquee a part par randomBrightness,
% car imageDataAugmenter ne la propose pas.
if nargin < 1, cfg = trainingConfig(); end
a = cfg.aug;
augmenter = imageDataAugmenter( ...
    'RandRotation',     a.rotation, ...
    'RandXReflection',  a.reflectionX, ...
    'RandScale',        a.scale, ...
    'RandXTranslation', a.translation, ...
    'RandYTranslation', a.translation);
end
